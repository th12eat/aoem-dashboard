#!/usr/bin/env node
/**
 * gen-restore-research.mjs — emit a SURGICAL SQL that restores each occurrence's
 * `research` roster (alliances + PLAYERS) from the backfill (07) into the DB.
 *
 * Why this exists: an EARLY, buggy run of 09-set-outcomes.sql overwrote the
 * `research` key on 14 occurrences with alliance-only data harvested from
 * history.json — wiping the per-player scouting lists that 07 had put there
 * (from each event's own JSON: ourTop/krakens/positional tuples). Re-running
 * the (now-fixed) 09 can't undo that: it simply stops touching those docs. The
 * players must be put back from their source of truth, which is 07.
 *
 * This emits one `doc = doc || '{"research": …}'::jsonb` per affected occurrence
 * — a RESEARCH-KEY-ONLY merge, so every other key you've edited since (stage
 * points, scoreboard, placement, result, star, map, …) is left untouched.
 * Only occurrences whose 07 doc actually carries players are rewritten.
 *
 * Output: supabase/10-restore-research.sql — paste + Run. Idempotent (writes the
 * same research back every time). Depends on 04 + 07. Run after 07/08/09.
 * Run: `node scripts/gen-restore-research.mjs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const V2 = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const q = s => `'${String(s).replace(/'/g, "''")}'`;

/** Parse 07 into a (slug|date → doc) map, splitting per-occurrence block first
 * so the jsonb literal's escaped quotes can't confuse a single mega-regex. */
function parseBackfill() {
  const bf = readFileSync(resolve(V2, 'supabase/07-backfill-events.sql'), 'utf8');
  const map = new Map();
  for (const block of bf.split(/\bWITH up AS \(/).slice(1)) {
    const head = block.match(/VALUES \('([a-z]+)', '([\d-]+)'/);
    const body = block.match(/SELECT id, '((?:[^']|'')*)'::jsonb FROM up/);
    if (!head || !body) continue;
    try {
      map.set(`${head[1]}|${head[2]}`, JSON.parse(body[1].replace(/''/g, "'")));
    } catch {
      /* skip unparseable */
    }
  }
  return map;
}

/** Count players carried in a research block (ours + every opponent). */
function playerCount(r) {
  if (!r) return 0;
  const oursP = r.ours && Array.isArray(r.ours.players) ? r.ours.players.length : 0;
  const oppP = Array.isArray(r.opponents) ? r.opponents.reduce((a, o) => a + (o.players?.length ?? 0), 0) : 0;
  return oursP + oppP;
}

const docs = parseBackfill();

const lines = [];
lines.push('-- ============================================================================');
lines.push('-- 10-restore-research.sql — restore per-player scouting rosters from 07');
lines.push('-- ============================================================================');
lines.push('-- GENERATED by scripts/gen-restore-research.mjs. A SURGICAL per-key merge that');
lines.push('-- rewrites ONLY the `research` key from the backfill (07), undoing an early');
lines.push("-- 09 run that clobbered players with alliance-only history data. Everything");
lines.push('-- else in each doc is preserved. Depends on 04 + 07. Idempotent.');
lines.push('-- Paste + Run in the Supabase SQL editor (after 07/08/09).');
lines.push('-- ============================================================================');
lines.push('');
lines.push('BEGIN;');
lines.push('');

let n = 0;
const report = [];
for (const [key, doc] of docs) {
  const r = doc.research;
  const players = playerCount(r);
  if (players === 0) continue; // nothing to restore for this occurrence
  const [slug, date] = key.split('|');
  const patch = JSON.stringify({ research: r });
  lines.push(`-- ${slug} · ${date}  (restore research: ${players} players)`);
  lines.push('UPDATE event_data SET doc = doc || ' + q(patch) + '::jsonb');
  lines.push(`WHERE event_id = (SELECT id FROM events WHERE type_slug = ${q(slug)} AND start_date = ${q(date)});`);
  lines.push('');
  n++;
  report.push(`  ${slug.padEnd(11)} ${date}  ${players} players`);
}

lines.push("INSERT INTO schema_migrations (filename, note) VALUES");
lines.push("  ('10-restore-research.sql', 'restore per-player scouting rosters from 07 backfill')");
lines.push('  ON CONFLICT (filename) DO NOTHING;');
lines.push('');
lines.push('COMMIT;');
lines.push('');

writeFileSync(resolve(V2, 'supabase/10-restore-research.sql'), lines.join('\n'));
console.log(`Wrote ${n} research-restore merges → supabase/10-restore-research.sql`);
for (const r of report) console.log(r);
