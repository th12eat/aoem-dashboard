#!/usr/bin/env node
/**
 * gen-set-outcomes.mjs — emit a SURGICAL SQL that reconciles each completed
 * occurrence's OUTCOME + ROSTERS to v1.0 history.json (the KvK History source
 * of truth), without clobbering anything else in the doc.
 *
 * Merges three keys per occurrence (jsonb `||`), only when history.json has
 * them and they'd actually change/add something:
 *   • result    — Win/Loss (already in 08; re-stamped here harmlessly)
 *   • placement — 1–4 for multi-kingdom events (the explicit v1.0 placement is
 *                 authoritative; the DB's score-derived rank was mis-keyed by
 *                 "Era 008" vs "Era 8")
 *   • research  — top-4 rosters for events whose own JSON stored none
 *                 (e.g. Behemoth: scalar scores only)
 *
 * Output: supabase/09-set-outcomes.sql — paste + Run. Idempotent. Safe over
 * 08 and any hand edits (only touches these keys). Depends on 04 + 07.
 * Run: `node scripts/gen-set-outcomes.mjs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const V2 = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = resolve(V2, '..');

function slugFor(name) {
  const n = name.toLowerCase();
  if (n.includes('storm')) return 'stormlands';
  if (n.includes('desolate')) return 'desolate';
  if (n.includes('primordial')) return 'primordial';
  if (n.includes('behemoth')) return 'behemoth';
  if (n === 'tme' || n.includes('mightiest empire')) return 'tme';
  return '';
}
const q = s => `'${String(s).replace(/'/g, "''")}'`;
const normServer = s => {
  const d = String(s).replace(/\D/g, '');
  return d ? `Era ${parseInt(d, 10)}` : String(s);
};
const toAlliance = r => ({ tag: String(r[0] ?? ''), name: String(r[0] ?? ''), power: r[1] ?? 0, merits: r[2] ?? 0 });

function researchFromHistory(e) {
  const ours = e.ours ?? e.ourRoster ?? [];
  let opponents = [];
  if (e.oppRosters) {
    opponents = Object.entries(e.oppRosters).map(([server, rows]) => ({ server: normServer(server), alliances: rows.map(toAlliance), players: [] }));
  } else if (e.oppA) {
    opponents = [{ server: e.opp ? normServer(e.opp) : 'Opponent', alliances: e.oppA.map(toAlliance), players: [] }];
  }
  if (!ours.length && !opponents.length) return null;
  return { ours: { server: 'Era 8', alliances: ours.map(toAlliance), players: [] }, opponents };
}

const history = JSON.parse(readFileSync(resolve(ROOT, 'data/history.json'), 'utf8'));
const events = (Array.isArray(history) ? history : history.events).filter(e => slugFor(e.event) && e.date);

const lines = [];
lines.push('-- ============================================================================');
lines.push('-- 09-set-outcomes.sql — reconcile result + placement + rosters to v1.0');
lines.push('-- ============================================================================');
lines.push('-- GENERATED by scripts/gen-set-outcomes.mjs from data/history.json (v1.0 KvK');
lines.push('-- History source of truth). SURGICAL per-key jsonb merges — leaves everything');
lines.push('-- else in each doc intact. Safe over 08 + hand edits. Depends on 04 + 07.');
lines.push('-- Paste + Run in the Supabase SQL editor. Idempotent.');
lines.push('-- ============================================================================');
lines.push('');
lines.push('BEGIN;');
lines.push('');

let n = 0;
for (const e of events) {
  const slug = slugFor(e.event);
  const patch = {};
  if (e.result === 'Win' || e.result === 'Loss') patch.result = e.result;
  if (typeof e.placement === 'number') patch.placement = e.placement;
  const research = researchFromHistory(e);
  if (research) patch.research = research;
  if (!Object.keys(patch).length) continue; // nothing to stamp (e.g. a bare Live)
  n++;
  const bits = Object.keys(patch).join(' + ');
  lines.push(`-- ${slug} · ${e.date}  (${bits})`);
  lines.push('UPDATE event_data SET doc = doc || ' + q(JSON.stringify(patch)) + '::jsonb');
  lines.push(`WHERE event_id = (SELECT id FROM events WHERE type_slug = ${q(slug)} AND start_date = ${q(e.date)});`);
  lines.push('');
}

lines.push("INSERT INTO schema_migrations (filename, note) VALUES");
lines.push("  ('09-set-outcomes.sql', 'result + placement + rosters reconciled to v1.0 history')");
lines.push('  ON CONFLICT (filename) DO NOTHING;');
lines.push('');
lines.push('COMMIT;');
lines.push('');

writeFileSync(resolve(V2, 'supabase/09-set-outcomes.sql'), lines.join('\n'));
console.log(`Wrote ${n} occurrence outcome-merges → supabase/09-set-outcomes.sql`);
for (const e of events) {
  const bits = [];
  if (e.result === 'Win' || e.result === 'Loss') bits.push(e.result);
  if (typeof e.placement === 'number') bits.push(`#${e.placement}`);
  if (researchFromHistory(e)) bits.push('rosters');
  if (bits.length) console.log(`  ${slugFor(e.event).padEnd(11)} ${e.date}  ${bits.join(' · ')}`);
}
