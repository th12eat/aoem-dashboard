#!/usr/bin/env node
/**
 * gen-set-results.mjs — emit a SURGICAL SQL that stamps each completed
 * occurrence's Win/Loss into its event_data doc, sourced from v1.0 history.json
 * (the KvK History source of truth). Unlike re-running the full backfill, this
 * only MERGES the `result` key (jsonb `||`), so any other hand-edited fields on
 * those occurrences are preserved.
 *
 * Output: supabase/08-set-results.sql — paste + Run in Supabase. Idempotent.
 * Run: `node scripts/gen-set-results.mjs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const V2 = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = resolve(V2, '..');

function slugFor(name) {
  const n = name.toLowerCase();
  if (n.includes('storm')) return 'stormlands';
  if (n.includes('desolate')) return 'desolate';
  if (n.includes('primordial')) return 'primordial';
  if (n.includes('behemoth')) return 'behemoth';
  if (n === 'tme' || n.includes('mightiest empire')) return 'tme';
  return '';
}
const q = s => `'${String(s).replace(/'/g, "''")}'`;

const history = JSON.parse(readFileSync(resolve(ROOT, 'data/history.json'), 'utf8'));
const events = Array.isArray(history) ? history : history.events;

const rows = events
  .map(e => ({ slug: slugFor(e.event), date: e.date, result: e.result }))
  // Only clean, decided outcomes — skip Live / TBD / unknown types.
  .filter(r => r.slug && r.date && (r.result === 'Win' || r.result === 'Loss'));

const lines = [];
lines.push('-- ============================================================================');
lines.push('-- 08-set-results.sql — stamp v1.0 Win/Loss onto each completed occurrence');
lines.push('-- ============================================================================');
lines.push('-- GENERATED by scripts/gen-set-results.mjs from data/history.json (the v1.0 KvK');
lines.push('-- History source of truth). SURGICAL: merges ONLY the `result` key into each');
lines.push('-- event_data doc (doc || \'{"result":...}\'), leaving every other field intact —');
lines.push('-- safe even if an occurrence was hand-edited. Idempotent. Depends on 04 + 07.');
lines.push(`-- ${rows.length} completed occurrences. Paste + Run in the Supabase SQL editor.`);
lines.push('-- ============================================================================');
lines.push('');
lines.push('BEGIN;');
lines.push('');
for (const r of rows) {
  lines.push(`-- ${r.slug} · ${r.date} → ${r.result}`);
  lines.push('UPDATE event_data SET doc = doc || ' + q(JSON.stringify({ result: r.result })) + '::jsonb');
  lines.push(`WHERE event_id = (SELECT id FROM events WHERE type_slug = ${q(r.slug)} AND start_date = ${q(r.date)});`);
  lines.push('');
}
lines.push('-- record in the migration ledger (00-schema-migrations)');
lines.push("INSERT INTO schema_migrations (filename, note) VALUES");
lines.push("  ('08-set-results.sql', 'v1.0 Win/Loss merged into completed occurrences')");
lines.push('  ON CONFLICT (filename) DO NOTHING;');
lines.push('');
lines.push('COMMIT;');
lines.push('');

const out = resolve(V2, 'supabase/08-set-results.sql');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${rows.length} result-merges → supabase/08-set-results.sql`);
for (const r of rows) console.log(`  ${r.slug.padEnd(11)} ${r.date}  ${r.result}`);
