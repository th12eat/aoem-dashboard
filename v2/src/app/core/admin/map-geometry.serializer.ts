import type { MapGeometry, MapNodeGeo, ServerBadgeGeo } from '@shared/models/map.model';

/**
 * Serialize a MapGeometry into a `<SLUG>_MAP` TS literal string matching the
 * hand-authored configs (src/app/configs/*.map.ts) closely enough to commit.
 *
 * Deliberate deviation from the hand-written files: buffs are emitted INLINE
 * rather than via a shared `BUFF_DEF` const — simpler + lossless. A header
 * comment marks the file as editor-generated.
 */

/** slug → const name: 'desolate-test' → 'DESOLATE_TEST_MAP'. */
export function constNameForSlug(slug: string): string {
  return slug.toUpperCase().replace(/[^A-Z0-9]+/g, '_') + '_MAP';
}

/** Integers without a decimal point; otherwise 1 dp. */
function fmtNum(n: number): string {
  return Number.isInteger(n) ? String(n) : String(Math.round(n * 10) / 10);
}

/** Single-quoted, escaping backslash + single quote. */
function str(s: string): string {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function serializeNode(n: MapNodeGeo): string {
  const parts: string[] = [
    `id: ${str(n.id)}`,
    `x: ${fmtNum(n.x)}`,
    `y: ${fmtNum(n.y)}`,
    `type: ${str(n.type)}`,
  ];
  if (n.subtype) parts.push(`subtype: ${str(n.subtype)}`);
  if (n.transition) parts.push(`transition: ${str(n.transition)}`);
  if (n.buff) parts.push(`buff: { key: ${str(n.buff.key)}, label: ${str(n.buff.label)}, magnitude: ${str(n.buff.magnitude)} }`);
  if (n.effect) parts.push(`effect: { label: ${str(n.effect.label)} }`);
  if (n.energyPerHour != null) parts.push(`energyPerHour: ${fmtNum(n.energyPerHour)}`);
  if (n.seed) parts.push(`seed: true`);
  parts.push(`label: ${str(n.label)}`);
  if (n.activeDayOffset != null) parts.push(`activeDayOffset: ${fmtNum(n.activeDayOffset)}`);
  return `    { ${parts.join(', ')} },`;
}

function serializeBadge(b: ServerBadgeGeo): string {
  return `    { server: ${str(b.server)}, x: ${fmtNum(b.x)}, y: ${fmtNum(b.y)} },`;
}

export function serializeGeometryToTs(geo: MapGeometry, slug: string): string {
  const name = constNameForSlug(slug);
  return [
    `import type { MapGeometry } from '@shared/models/map.model';`,
    ``,
    `/** ${slug} — map geometry. Generated by the admin map editor; edit there or by hand. */`,
    `export const ${name}: MapGeometry = {`,
    `  viewBox: ${str(geo.viewBox)},`,
    `  underlayAsset: ${str(geo.underlayAsset)},`,
    `  serverBadges: [`,
    ...geo.serverBadges.map(serializeBadge),
    `  ],`,
    `  nodes: [`,
    ...geo.nodes.map(serializeNode),
    `  ],`,
    `};`,
    ``,
  ].join('\n');
}
